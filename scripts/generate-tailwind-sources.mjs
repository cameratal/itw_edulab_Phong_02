// Tailwind v4 finds the classes it must generate by scanning the project with
// its native `oxide` addon. Smart App Control on this workstation refuses to
// load unsigned native .node addons, so oxide falls back to its WASM/WASI
// build -- and that build's file scanner returns zero files here, because its
// only preopened directory is the Windows drive root, which the Rust globwalk
// cannot traverse. The result is a stylesheet with a theme but no utilities.
//
// So we do the scanning ourselves: pull every string literal out of the
// sources, treat the whitespace-separated words as candidates, and hand them to
// Tailwind through `@source inline(...)`, which needs no file access at all.
// Unknown words are ignored by Tailwind, so over-collecting is harmless.
//
// Runs automatically via the `predev` / `prebuild` npm scripts. Re-run it after
// adding a class that was not already used somewhere in the project.

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "tailwind-sources.css");
const SOURCE_EXT = /\.(tsx?|jsx?|html)$/;

function collect(dir, found = []) {
  for (const entry of readdirSync(dir)) {
    const abs = join(dir, entry);
    if (statSync(abs).isDirectory()) {
      if (entry === "node_modules" || entry.startsWith(".")) continue;
      collect(abs, found);
    } else if (SOURCE_EXT.test(entry)) {
      found.push(abs);
    }
  }
  return found;
}

// Anything that cannot appear in a class name, or that would break out of the
// `@source inline("...")` string, disqualifies a word.
// Dấu phẩy và ngoặc KHÔNG cân là chí mạng. Tailwind gặp một mẩu như
// `linear-gradient(140deg,` trong @source inline(...) là bỏ luôn CẢ DÒNG đó,
// kéo theo mọi lớp hợp lệ đứng cùng dòng. Lỗi này đã làm bay sạch nhóm
// max-w-* nên trang mất canh giữa — nhìn như hỏng bố cục, rất khó truy ra.
const ILLEGAL = /["`\\{};,]/;

/** Ngoặc phải đóng mở cân nhau, không thì cả dòng @source inline hỏng theo. */
function canBang(word) {
  let tron = 0;
  let vuong = 0;
  for (const c of word) {
    if (c === "(") tron++;
    else if (c === ")") tron--;
    else if (c === "[") vuong++;
    else if (c === "]") vuong--;
    if (tron < 0 || vuong < 0) return false;
  }
  return tron === 0 && vuong === 0;
}
const CANDIDATE = /^[a-zA-Z0-9@!-][a-zA-Z0-9@!_:./#%()&,+*<>~=$[\]-]*$/;

const files = [join(ROOT, "index.html"), ...collect(join(ROOT, "src"))];
const candidates = new Set();

for (const file of files) {
  const code = readFileSync(file, "utf8");
  // Contents of double-quoted, single-quoted and template strings. className
  // values live in exactly these, whether static or inside a template literal.
  for (const m of code.matchAll(/"([^"\n]*)"|'([^'\n]*)'|`([^`]*)`/g)) {
    const body = m[1] ?? m[2] ?? m[3] ?? "";
    for (const word of body.split(/\s+/)) {
      if (!word || word.length > 120) continue;
      if (ILLEGAL.test(word) || !CANDIDATE.test(word)) continue;
      if (!canBang(word)) continue;
      candidates.add(word);
    }
  }
}

const words = [...candidates].sort();
const lines = [];
for (let i = 0; i < words.length; i += 40) {
  lines.push(`@source inline("${words.slice(i, i + 40).join(" ")}");`);
}

writeFileSync(
  OUT,
  `/* GENERATED by scripts/generate-tailwind-sources.mjs -- do not edit. */\n` +
    `/* ${words.length} candidates from ${files.length} files. */\n\n` +
    lines.join("\n") +
    "\n",
  "utf8",
);

console.log(
  `tailwind-sources.css: ${words.length} candidates from ${files.length} files`,
);
